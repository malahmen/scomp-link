main() {
    preflight_checks

    gum style \
        --foreground "$CYAN" --border-foreground "$CYAN" --border double \
        --align center --width 60 --margin "1 2" --padding "1 4" \
        'Starlight Manager'

    while true; do
        return_to_origin

        local project_list
        project_list=$(scan_projects)

        if [[ -z "$project_list" ]]; then
            gum style \
                --foreground "$YELLOW" --border-foreground "$YELLOW" --border rounded \
                --align center --width 60 --margin "1 2" --padding "1 2" \
                "No Starlight projects found in this directory tree."

            local choice
            choice=$(gum choose \
                "Create new project" \
                "Create site over an existing folder" \
                "Refresh" \
                "Quit" \
                --header "What would you like to do?") || true

            case "$choice" in
                "Create new project") create_project_flow ;;
                "Create site over an existing folder") create_external_flow ;;
                "Refresh")            continue ;;
                "Quit"|"")            break ;;
            esac
            continue
        fi

        # Build menu: create option + found projects + quit
        local menu_items=("── create new project ──" "── create site over an existing folder ──")
        while IFS= read -r proj; do
            menu_items+=("$proj")
        done <<< "$project_list"
        menu_items+=("── quit ──")

        local selection
        selection=$(printf '%s\n' "${menu_items[@]}" | gum choose \
            --header "Select a project ($(echo "$project_list" | wc -l | tr -d ' ') found):") || true

        case "$selection" in
            "── create new project ──")
                create_project_flow
                ;;
            "── create site over an existing folder ──")
                create_external_flow
                ;;
            "── quit ──"|"")
                break
                ;;
            *)
                # Resolve to absolute path
                local abs_path
                if [[ "$selection" == "." ]]; then
                    abs_path="$ORIGIN_DIR"
                elif [[ "$selection" == /* ]]; then
                    abs_path="$selection"          # a site under STARLIGHT_HOME
                else
                    abs_path="${ORIGIN_DIR}/${selection}"
                fi

                if [[ ! -d "$abs_path" ]]; then
                    warn "Directory '${selection}' no longer exists."
                    continue
                fi

                if [[ ! -f "${abs_path}/${CONFIG_FILE}" ]]; then
                    warn "'${selection}' is no longer a valid Starlight project."
                    continue
                fi

                PROJECT_DIR="$abs_path"
                manage_menu
                ;;
        esac
    done

    echo ""
    success "Done. Run 'bash init.sh' inside your project to preview changes."
}

main "$@"
