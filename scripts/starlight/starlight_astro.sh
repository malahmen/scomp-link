# =============================================================================
# EXTERNAL SITES — a Starlight site over an existing folder of Markdown
# =============================================================================
#
# The documents stay where they are (e.g. a reports repository): the generated
# content collection loads them from that folder by absolute path, so nothing
# is copied into the project and nothing is written into the folder. The
# project itself (node_modules, dist/) lives elsewhere — by default under
# STARLIGHT_HOME — and serves the folder live with `astro dev`.

# resolve_source_dir <path> — absolute, symlink-free path of an existing
# directory (with a leading ~ expanded), or empty.
resolve_source_dir() {
    local p="$1"
    [[ "$p" == "~"* ]] && p="${HOME}${p:1}"
    [[ -d "$p" ]] || return 0
    (cd "$p" && pwd -P)
}

# count_source_docs <dir> — Markdown/MDX files the site will serve.
count_source_docs() {
    find "$1" \( -name node_modules -o -name .git \) -prune -o \
        -type f \( -name '*.md' -o -name '*.mdx' \) -print 2>/dev/null | wc -l | tr -d ' '
}

# pick_source_dir [current] — ask for the folder to serve; echoes its absolute
# path, or nothing on cancel / invalid input (with a warning).
pick_source_dir() {
    local current="${1:-$ORIGIN_DIR}" raw dir n
    raw=$(gum input --width 70 --value "$current" \
        --placeholder "Folder with the Markdown documents (absolute or ~/...)" \
        --char-limit 512) || true
    [[ -z "$raw" ]] && { warn "Cancelled."; return 0; }
    dir=$(resolve_source_dir "$raw")
    [[ -z "$dir" ]] && { warn "Not a directory: ${raw}"; return 0; }
    n=$(count_source_docs "$dir")
    if [[ "$n" -eq 0 ]]; then
        warn "No .md/.mdx files under ${dir}."
        return 0
    fi
    info "${n} Markdown file(s) under ${dir}."
    printf '%s' "$dir"
}

# write_external_site_files <project_dir> <source_dir> <title> <description>
# Everything that makes the project read its documents from <source_dir>.
write_external_site_files() {
    local proj="$1" src="$2" title="$3" desc="$4"
    local safe_title="${title//\'/\\\'}" safe_desc="${desc//\'/\\\'}"

    printf '%s\n' "$src" > "${proj}/${SOURCE_FILE}"

    # The template's own pages would otherwise be served next to the external
    # ones; the collection below never reads src/content/docs.
    rm -rf "${proj:?}/src/content/docs"

    cat > "${proj}/src/content.config.ts" <<'TSEOF'
// Starlight's docs collection, loaded from a folder OUTSIDE this project.
// The folder is named in ../.docs-source (or $DOCS_SOURCE); nothing is copied.
import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { docsSchema } from '@astrojs/starlight/schema';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DOCS_SOURCE, docId } from './external-docs.mjs';

// glob(), plus a title for documents without one: Starlight requires a
// front-matter `title`, so a file that has none takes its first "# " heading
// (or, failing that, its file name).
function externalDocs(base) {
  const inner = glob({
    base,
    pattern: ['**/*.{md,mdx}', '!**/node_modules/**', '!**/.git/**'],
    generateId: ({ entry }) => docId(entry),
  });
  return {
    name: 'external-docs',
    load: (ctx) =>
      inner.load({
        ...ctx,
        parseData: async (entry) => {
          if (!entry.data?.title && entry.filePath) {
            const file = path.resolve(fileURLToPath(ctx.config.root), entry.filePath);
            const h1 = (await readFile(file, 'utf8')).match(/^#\s+(.+?)\s*$/m);
            entry = { ...entry, data: { ...entry.data, title: h1 ? h1[1] : entry.id } };
          }
          return ctx.parseData(entry);
        },
      }),
  };
}

export const collections = {
  docs: defineCollection({ loader: externalDocs(DOCS_SOURCE), schema: docsSchema() }),
};
TSEOF

    cat > "${proj}/src/external-docs.mjs" <<'MJSEOF'
// Shared by content.config.ts and astro.config.mjs for a site over an external
// folder: where the documents are, how a file maps to a page, and two remark
// plugins that make plain Markdown documents read well as Starlight pages.
import { readFileSync } from 'node:fs';
import path from 'node:path';

const sourceFile = new URL('../.docs-source', import.meta.url);
export const DOCS_SOURCE = (process.env.DOCS_SOURCE || readFileSync(sourceFile, 'utf8')).trim();

// review-2026-10-02.md -> review-2026-10-02 ; README.md (any folder) -> index.
export function docId(relPath) {
  const id = relPath.replace(/\.mdx?$/i, '').toLowerCase();
  if (id === 'readme') return 'index';
  return id.endsWith('/readme') ? id.slice(0, -'/readme'.length) : id;
}

const insideSource = (file) => typeof file?.path === 'string' && file.path.startsWith(DOCS_SOURCE + path.sep);

// Starlight renders the title as the page's H1. A document that opens with
// its own "# Title" would show it twice, so drop an H1 that is the very first
// node. H1s further down (e.g. "# Round 2") are kept.
export function remarkDropLeadingH1() {
  return (tree, file) => {
    if (!insideSource(file)) return;
    const first = tree.children.find((n) => n.type !== 'yaml' && n.type !== 'toml');
    if (first && first.type === 'heading' && first.depth === 1) tree.children.splice(tree.children.indexOf(first), 1);
  };
}

// Links between documents are written as files ("[x](other.md#part)"); on the
// site they must be page URLs ("/other/#part"). Only relative .md/.mdx links
// that resolve inside the source folder are rewritten.
export function remarkMdLinksToPages() {
  return (tree, file) => {
    if (!insideSource(file)) return;
    const visit = (node) => {
      if (node.type === 'link' || node.type === 'definition') {
        const m = /^([^?#]+\.mdx?)(#.*)?$/i.exec(node.url || '');
        if (m && !/^[a-z][a-z0-9+.-]*:/i.test(node.url) && !node.url.startsWith('/')) {
          const target = path.resolve(path.dirname(file.path), decodeURI(m[1]));
          const rel = path.relative(DOCS_SOURCE, target);
          if (!rel.startsWith('..') && !path.isAbsolute(rel)) {
            const id = docId(rel.split(path.sep).join('/'));
            node.url = (id === 'index' ? '/' : `/${id}/`) + (m[2] || '');
          }
        }
      }
      node.children?.forEach(visit);
    };
    visit(tree);
  };
}
MJSEOF

    cat > "${proj}/astro.config.mjs" <<CONFIGEOF
// Starlight site over an external folder (see .docs-source). Sidebar: every
// document, generated from the folder's file tree.
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import { unified } from '@astrojs/markdown-remark';
import { DOCS_SOURCE, remarkDropLeadingH1, remarkMdLinksToPages } from './src/external-docs.mjs';

// https://astro.build/config
export default defineConfig({
  markdown: {
    processor: unified({ remarkPlugins: [remarkDropLeadingH1, remarkMdLinksToPages] }),
  },
  // The dev server may read files (e.g. images) from the external folder.
  vite: { server: { fs: { allow: ['.', DOCS_SOURCE] } } },
  integrations: [
    starlight({
      title: '${safe_title}',
      description: '${safe_desc}',
    }),
  ],
});
CONFIGEOF

    cat > "${proj}/mise.toml" <<'MISEEOF'
[tasks.dev]
description = "Serve the external folder live (reloads on edits)"
run = "npm run dev"

[tasks.build]
description = "Build the static site into dist/ (inside this project, never the source)"
run = "npm run build"

[tasks.preview]
description = "Preview the production build"
run = "npm run preview"
MISEEOF
}

# Create a Starlight site that serves an existing folder in place.
create_external_flow() {
    header "New Site Over an Existing Folder"
    info "The documents are read where they are: nothing is copied into the site,"
    info "and nothing is written into the folder."
    return_to_origin

    local src
    src=$(pick_source_dir "$ORIGIN_DIR")
    [[ -z "$src" ]] && return

    local name
    name=$(gum input --width 60 --value "$(basename "$src")" \
        --placeholder "Site title" --char-limit 64) || true
    [[ -z "$name" ]] && { warn "Cancelled."; return; }
    local slug; slug=$(slugify "$name")
    [[ -z "$slug" ]] && { warn "The title produced an empty folder name."; return; }

    local desc
    desc=$(gum input --width 60 --placeholder "Description (optional)" --char-limit 160) || true
    [[ -z "$desc" ]] && desc="Documents from ${src}"

    local home_opt="${STARLIGHT_HOME}/${slug}" here_opt="${ORIGIN_DIR}/${slug}" where
    where=$(gum choose --header "Where should the site project live?" \
        "${home_opt}  (outside any repository)" \
        "${here_opt}  (here)") || true
    [[ -z "$where" ]] && { warn "Cancelled."; return; }
    local proj="${where%%  (*}"

    # The point is to keep the site out of the documents' folder.
    if [[ "$proj/" == "$src/"* ]]; then
        warn "${proj} is inside the source folder — pick a location outside it."
        return
    fi
    if [[ -e "$proj" ]]; then
        warn "${proj} already exists — choose another title or remove it first."
        return
    fi

    local parent; parent="$(dirname "$proj")"
    mkdir -p "$parent" || { warn "Cannot create ${parent}."; return; }

    header "Scaffolding Starlight"
    if ! (cd "$parent" && gum spin --spinner dot --title "Creating Starlight project in ${proj} ..." -- \
            npm create astro@latest "$slug" -- --template starlight --yes --no-install --no-git); then
        warn "Scaffolding failed."
        return
    fi
    [[ -f "${proj}/package.json" ]] || { warn "Scaffolding failed — ${proj} was not created."; return; }

    if ! (cd "$proj" && gum spin --spinner dot --title "Installing dependencies ..." -- npm install \
            && gum spin --spinner dot --title "Installing @astrojs/markdown-remark ..." -- \
                npm install @astrojs/markdown-remark); then
        warn "npm install failed in ${proj}."
        return
    fi
    success "Dependencies installed."

    write_external_site_files "$proj" "$src" "$name" "$desc"
    (cd "$proj" && command -v mise &>/dev/null && mise trust mise.toml >/dev/null 2>&1) || true
    (cd "$proj" && create_write_init_script)
    success "Site ready: ${proj}"
    info "Source: ${src} (stored in ${SOURCE_FILE})"

    PROJECT_DIR="$proj"
    manage_menu
}

# --- managing an external site -------------------------------------------------

external_source() { tr -d '\n' < "$SOURCE_FILE" 2>/dev/null; }

change_external_source() {
    header "Change Source Folder"
    info "Current: $(external_source)"
    local src
    src=$(pick_source_dir "$(external_source)")
    [[ -z "$src" ]] && return
    if [[ "$PROJECT_DIR/" == "$src/"* ]]; then
        warn "This site lives inside ${src}; pick a folder that does not contain it."
        return
    fi
    printf '%s\n' "$src" > "$SOURCE_FILE"
    success "Source set to ${src}. Restart a running dev server to pick it up."
}

external_serve() {
    local host_flag=()
    local mode
    mode=$(gum choose --header "Serve to:" "this machine only (localhost)" "the network (--host)") || true
    [[ -z "$mode" ]] && { warn "Cancelled."; return; }
    [[ "$mode" == "the network"* ]] && host_flag=(-- --host)
    [[ -d node_modules ]] || { info "Installing dependencies..."; npm install || { warn "npm install failed."; return; }; }
    info "Serving $(external_source) — edits show up on reload. Ctrl-C to stop."
    run_foreground npm run dev ${host_flag[@]+"${host_flag[@]}"}
}

external_manage_menu() {
    while true; do
        header "Managing: $(basename "$PROJECT_DIR") (external)"
        info "Source: $(external_source)"
        [[ -d "$(external_source)" ]] || warn "The source folder no longer exists — change it below."

        local options=(
            "Serve (dev server, live)"
            "Build static site (dist/)"
            "Preview the build"
            "Change source folder"
            "Edit astro.config.mjs"
        )
        [[ $HAS_TREE -eq 1 ]] && options+=("View site structure")
        options+=("Delete this site" "── ──" "Switch project" "Quit")

        local choice
        choice=$(printf '%s\n' "${options[@]}" | gum choose \
            --header "What would you like to do?" --height 14) || true
        [[ -z "$choice" ]] && return

        case "$choice" in
            "Serve (dev server, live)")   external_serve ;;
            "Build static site (dist/)")  run_foreground npm run build ;;
            "Preview the build")
                if [[ -d dist ]]; then run_foreground npm run preview
                else warn "No dist/ yet — build first."; fi ;;
            "Change source folder")       change_external_source ;;
            "Edit astro.config.mjs")      edit_config ;;
            "View site structure")        view_structure ;;
            "Delete this site")           if delete_project; then return_to_origin; return; fi ;;
            "Switch project")             return_to_origin; return ;;
            "Quit")                       return ;;
            "── "*)                       continue ;;
        esac
    done
}

