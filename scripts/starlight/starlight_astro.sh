create_collect_project_info() {
    header "New Project — Setup"

    PROJECT_NAME=$(gum input --width 60 \
        --placeholder "Project name (e.g. my-docs)" \
        --char-limit 64) || true
    [[ -z "$PROJECT_NAME" ]] && { warn "Cancelled."; return 1; }

    PROJECT_SLUG=$(slugify "$PROJECT_NAME")
    [[ -z "$PROJECT_SLUG" ]] && { warn "Project name produced an empty slug."; return 1; }

    if [[ -d "${ORIGIN_DIR}/${PROJECT_SLUG}" ]]; then
        warn "Directory '${PROJECT_SLUG}' already exists."
        if ! gum confirm "Continue anyway? (existing files may conflict)"; then
            warn "Cancelled."
            return 1
        fi
    fi

    SITE_DESCRIPTION=$(gum input --width 60 \
        --placeholder "Site description (e.g. Documentation for ${PROJECT_NAME})" \
        --char-limit 160) || true
    [[ -z "$SITE_DESCRIPTION" ]] && SITE_DESCRIPTION="Documentation for ${PROJECT_NAME}"

    if gum confirm "Enable Mermaid diagram support?"; then
        ENABLE_MERMAID=true
        info "Mermaid support enabled — diagrams will render in the browser and in PDF exports."
    else
        ENABLE_MERMAID=false
    fi

    success "Project: ${PROJECT_NAME} → ./${PROJECT_SLUG}"
}

create_scaffold() {
    header "Scaffolding Starlight"

    info "Running: npm create astro@latest ${PROJECT_SLUG} -- --template starlight --yes --no-install"

    gum spin --spinner dot --title "Creating Starlight project in ./${PROJECT_SLUG} ..." -- \
        npm create astro@latest "$PROJECT_SLUG" -- --template starlight --yes --no-install

    [[ ! -d "${ORIGIN_DIR}/${PROJECT_SLUG}" ]] && { warn "Scaffolding failed — directory not created."; return 1; }
    success "Scaffolded at ./${PROJECT_SLUG}"

    cd "${ORIGIN_DIR}/${PROJECT_SLUG}" || { warn "Could not enter ./${PROJECT_SLUG}."; return 1; }

    gum spin --spinner dot --title "Installing dependencies ..." -- \
        npm install

    if [[ "$ENABLE_MERMAID" == "true" ]]; then
        # The Mermaid remark plugin needs the unified() processor (see
        # create_build_config); Astro 7 no longer installs it by default.
        gum spin --spinner dot --title "Installing @astrojs/markdown-remark (Mermaid) ..." -- \
            npm install @astrojs/markdown-remark
    fi

    success "Dependencies installed."

    # ── converter/ folder ────────────────────────────────────────────────────
    header "Setting Up Converter"

    mkdir -p converter

    # Vendor the holo-convert engine (holo-convert.sh + .fcc) plus the project
    # front-end (convert.sh) so the scaffolded project is fully self-contained —
    # no runtime dependency on scomp-link. The engine is gum-free and needs no
    # ui.sh; convert.sh is the project's own gum front-end.
    local converter_script="${SCRIPT_DIR}/converter/convert.sh"

    # Locate the engine: $HOLO_CONVERT_DIR → sibling checkout → cache → clone.
    local repo="${HOLO_CONVERT_REPO:-https://github.com/malahmen/holo-convert.git}"
    local cache="${XDG_CACHE_HOME:-$HOME/.cache}/scomp-link/holo-convert"
    local engine=""
    if [[ -n "${HOLO_CONVERT_DIR:-}" && -f "${HOLO_CONVERT_DIR}/holo-convert.sh" ]]; then
        engine="${HOLO_CONVERT_DIR}/holo-convert.sh"
    elif [[ -f "${SCRIPT_DIR}/../../../holo-convert/holo-convert.sh" ]]; then
        engine="$(cd "${SCRIPT_DIR}/../../../holo-convert" && pwd)/holo-convert.sh"
    elif [[ -f "${cache}/holo-convert.sh" ]]; then
        engine="${cache}/holo-convert.sh"
    elif command -v git &>/dev/null && gum confirm "Fetch the holo-convert engine from ${repo}?"; then
        mkdir -p "$(dirname "$cache")"
        if gum spin --spinner dot --title "Cloning holo-convert..." -- \
                git clone --depth 1 "$repo" "$cache"; then
            engine="${cache}/holo-convert.sh"
        fi
    fi

    if [[ -f "$converter_script" ]]; then
        cp "$converter_script" converter/convert.sh
        chmod +x converter/convert.sh
        success "convert.sh (front-end) copied to converter/"
    else
        warn "converter/convert.sh not found at ${converter_script} — skipping."
    fi

    if [[ -n "$engine" && -f "$engine" ]]; then
        cp "$engine" converter/holo-convert.sh
        chmod +x converter/holo-convert.sh
        success "holo-convert engine vendored into converter/"
        local fcc_source; fcc_source="$(cd "$(dirname "$engine")" && pwd)/.fcc"
        if [[ -d "$fcc_source" ]]; then
            rm -rf converter/.fcc
            cp -r "$fcc_source" converter/.fcc
            success ".fcc/ assets copied to converter/.fcc/"
        else
            warn ".fcc/ not found next to the engine (${fcc_source}) — conversions may fail."
            mkdir -p converter/.fcc/pdf converter/.fcc/title-pages
        fi
    else
        warn "holo-convert engine not found — the converter won't run until you place"
        warn "holo-convert.sh + .fcc/ in converter/ (get it from ${repo}, or set HOLO_CONVERT_DIR)."
        mkdir -p converter/.fcc/pdf converter/.fcc/title-pages
    fi

    success "converter/ ready."

    # ── mise.toml ────────────────────────────────────────────────────────────
    local mermaid_tool=""
    if [[ "$ENABLE_MERMAID" == "true" ]]; then
        mermaid_tool=$'\n'"\"npm:@mermaid-js/mermaid-cli\" = \"11.12.0\""
    fi

    cat > mise.toml << MISEEOF
[tools]${mermaid_tool}

[tasks.dev]
description = "Start Starlight dev server"
run = "npm run dev"

[tasks.build]
description = "Build the Starlight site"
run = "npm run build"

[tasks.preview]
description = "Preview the production build"
run = "npm run preview"

[tasks.convert]
description = "Convert docs interactively (pick files, choose format + options)"
run = "bash converter/convert.sh"

[tasks."convert:pdf"]
description = "Convert docs to PDF (file picker; title page + TOC, rules stripped)"
run = "bash converter/convert.sh pdf"

[tasks."convert:docx"]
description = "Convert docs to DOCX (file picker; styled, with TOC)"
run = "bash converter/convert.sh docx"
MISEEOF

    mise trust mise.toml

    gum spin --spinner dot --title "Installing mise tools (this may take a moment)..." -- \
        mise install

    success "mise.toml created, trusted, and tools installed."
}

