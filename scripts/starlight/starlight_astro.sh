manage_menu() {
    # Ensure we're in the project directory
    cd "$PROJECT_DIR" || error_exit "Cannot enter project directory: ${PROJECT_DIR}"

    if [[ -f "$SOURCE_FILE" ]]; then
        # Its pages belong to the source folder, so the page/section editing
        # actions below don't apply.
        external_manage_menu
        return
    fi
    migrate_sidebar_format

    while true; do
        local project_label
        project_label=$(basename "$PROJECT_DIR")

        header "Managing: ${project_label}"

        local options=(
            "── Sections ──"
            "Add section"
            "Rename section"
            "Remove section"
            "Reorder sections"
            "── Files ──"
            "Add file"
            "Edit file"
            "Rename file"
            "Move file"
            "Delete file"
            "── Site ──"
            "Edit homepage"
            "Edit astro.config.mjs"
        )

        [[ $HAS_TREE -eq 1 ]] && options+=("View site structure")
        options+=("Delete this project")

        options+=("── ──" "Switch project" "Quit")

        local choice
        choice=$(printf '%s\n' "${options[@]}" | gum choose \
            --header "What would you like to do?" \
            --height 20) || true

        [[ -z "$choice" ]] && break

        case "$choice" in
            "Add section")            add_section ;;
            "Rename section")         rename_section ;;
            "Remove section")         remove_section ;;
            "Reorder sections")       reorder_sections ;;
            "Add file")               add_file ;;
            "Edit file")              edit_file ;;
            "Rename file")            rename_file ;;
            "Move file")              move_file ;;
            "Delete file")            delete_file ;;
            "Edit homepage")          edit_homepage ;;
            "Edit astro.config.mjs")  edit_config ;;
            "View site structure")    view_structure ;;
            "Delete this project")
                if delete_project; then return_to_origin; return; fi ;;
            "Switch project")
                return_to_origin
                return   # Back to main loop — will show project list
                ;;
            "Quit") break ;;
            "── "*) continue ;;  # Section headers — not selectable
        esac
    done
}

