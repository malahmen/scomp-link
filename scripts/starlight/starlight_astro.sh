        --placeholder "Short description (optional)" \
        --char-limit 200) || true

    cat > "$filepath" << PAGEEOF
---
title: ${title}
description: ${description}
---

## ${title}

Write your content here.
PAGEEOF

    success "Created: ${filepath}"

    if gum confirm "Open in vim now?"; then
        vim "$filepath"
    fi
}

