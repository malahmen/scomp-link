#!/usr/bin/env bash
# description: Create and manage Starlight documentation sites
# Standalone export (export.sh): tools the slimmed setup.sh pre-installs.
# export-setup: node tree vim
# -----------------------------------------------------------------------------
# starlight_astro.sh
# Interactive TUI for creating and managing Astro Starlight documentation projects.
# Called by init.sh — expects gum to already be available.
# Dependencies: gum (managed by init.sh), node (>= 22.12; odd majors warn), npm, vim; mise recommended; tree optional
# Optional: tree (site structure view)
# -----------------------------------------------------------------------------

# Intentionally NOT using `set -e`: this script is an interactive TUI with many
# gum prompts that return non-zero on cancel; -e would abort on every cancel.
# Errors are checked explicitly where they matter.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# -----------------------------------------------------------------------------
# Bash version guard — requires bash 4+ (associative arrays, nameref, etc.)
# macOS ships bash 3.2; install via brew and ensure it's first on PATH.
# -----------------------------------------------------------------------------
if [[ "${BASH_VERSINFO[0]}" -lt 4 ]]; then
    echo "[error] bash 4 or higher is required (you have bash ${BASH_VERSION})."
    echo "  On macOS: brew install bash"
    echo "  Then ensure /opt/homebrew/bin or /usr/local/bin is before /usr/bin in PATH."
    exit 1
fi

if [[ -d "${SCRIPT_DIR}/../_common" ]]; then
    COMMON_DIR="${SCRIPT_DIR}/../_common"   # scomp-link repo layout
else
    COMMON_DIR="${SCRIPT_DIR}"              # exported standalone: deps sit alongside
fi
if [[ ! -d "$COMMON_DIR" ]]; then
    printf "\033[0;31m[ERROR] _common directory not found at %s\033[0m\n" "$COMMON_DIR" >&2
    exit 1
fi
# shellcheck source=../_common/ui.sh
source "${COMMON_DIR}/ui.sh"

# -----------------------------------------------------------------------------
# Constants & colours
# -----------------------------------------------------------------------------

# Script-level globals
ORIGIN_DIR="$(pwd)"        # Directory the script was launched from
PROJECT_DIR=""             # Currently active project directory
HAS_TREE=0

# Globals set during create flow
PROJECT_NAME=""
PROJECT_SLUG=""
SITE_DESCRIPTION=""
SIDEBAR_ENTRIES=()
EXTERNAL_LINKS=()
ENABLE_MERMAID=false

# Globals used by management
DOCS_DIR="src/content/docs"
CONFIG_FILE="astro.config.mjs"

# Sites built over an existing folder ("external" sites) keep the absolute path
# of that folder here, in the project root. Its presence is what marks a project
# as external: the documents are read in place, never copied into the project.
SOURCE_FILE=".docs-source"
# Where external sites are created by default: outside any repository, so the
# Astro project, node_modules and dist/ never land inside the documents' repo.
STARLIGHT_HOME="${SCOMP_STARLIGHT_HOME:-${XDG_DATA_HOME:-$HOME/.local/share}/scomp-link/starlight}"

slugify() {
    echo "$1" | tr '[:upper:]' '[:lower:]' | tr ' ' '-' | tr -cd '[:alnum:]-_'
}

# sidebar_autogen_entry <label> <folder> — one autogenerated sidebar group.
# Starlight 0.39 dropped `{ label, autogenerate }` groups: a group is now a
# label plus an `items` array holding the autogenerate config. Older Starlight
# releases accept this form too, so it is the only one written.
sidebar_autogen_entry() {
    printf "{ label: '%s', items: [{ autogenerate: { directory: '%s' } }] }" "$1" "$2"
}

# The pre-0.39 group shape, as written by earlier versions of this script.
OLD_SIDEBAR_RE="\\{ label: '([^']*)', autogenerate: \\{ directory: '([^']*)' \\} \\}"

# Offer to rewrite old-format sidebar groups in the current project's config.
# Starlight >= 0.39 refuses to build with them ("Support for autogenerated
# sidebar groups was removed").
migrate_sidebar_format() {
    [[ -f "$CONFIG_FILE" ]] || return 0
    grep -Eq "$OLD_SIDEBAR_RE" "$CONFIG_FILE" || return 0
    warn "astro.config.mjs uses the old sidebar group format, which Starlight 0.39+ rejects."
    gum confirm "Convert it to the current format now?" || { info "Left as is."; return 0; }
    sed -E -i.bak "s/${OLD_SIDEBAR_RE}/{ label: '\\1', items: [{ autogenerate: { directory: '\\2' } }] }/g" "$CONFIG_FILE" \
        && rm -f "${CONFIG_FILE}.bak"
    success "Sidebar converted."
}

# run_foreground <cmd...> — run a long-lived command (dev server, preview) so
# that Ctrl-C stops the command and returns to the menu instead of killing the TUI.
run_foreground() {
    trap ':' INT
    "$@" || true
    trap - INT
}

# Returns to ORIGIN_DIR — called before any operation that needs to rescan
return_to_origin() {
    cd "$ORIGIN_DIR" || error_exit "Cannot return to origin directory: ${ORIGIN_DIR}"
}

# -----------------------------------------------------------------------------
# Preflight checks
# -----------------------------------------------------------------------------

preflight_checks() {
    if ! command -v gum &>/dev/null; then
        echo "[error] gum is not installed. Please run setup.sh first."
        exit 1
    fi

    if ! command -v npm &>/dev/null; then
        error_exit "npm is not installed. Please run setup.sh to install Node.js/npm, then re-run."
    fi

    local node_major node_minor
    node_major=$(node -e "process.stdout.write(String(process.versions.node.split('.')[0]))")
    node_minor=$(node -e "process.stdout.write(String(process.versions.node.split('.')[1]))")
    # Current Astro dropped Node 18 and 20 — the floor is Node v22.12.0, and
    # `npm create astro@latest` pulls the newest engine, so anything older fails
    # mid-scaffold. Odd-numbered majors (23, 25, …) are not on Astro's support
    # list but work in practice, so they only warn. setup.sh will not replace an
    # existing node, hence the explicit mise hint.
    if [[ "$node_major" -lt 22 ]] || { [[ "$node_major" -eq 22 ]] && [[ "$node_minor" -lt 12 ]]; }; then
        error_exit "Node.js $(node --version) is too old for current Astro (needs v22.12.0+). Install an LTS: mise use --global node@lts"
    fi
    if (( node_major % 2 != 0 )); then
        warn "Node.js $(node --version) is an odd-numbered release; Astro officially supports even (LTS) majors only. Works in practice — switch with: mise use --global node@lts"
    fi

    if ! command -v vim &>/dev/null; then
        error_exit "vim is not installed. Please run setup.sh first."
    fi

    # 'create' (scaffold) calls 'mise trust'/'mise install', and every generated
    # mise.toml task needs it. Not fatal (managing existing projects works without
    # it), but warn so the failure isn't silent under set -uo pipefail.
    if ! command -v mise &>/dev/null; then
        warn "mise not found — 'create' and the generated mise.toml tasks require it. Install via setup.sh."
    fi

    if command -v tree &>/dev/null; then
        HAS_TREE=1
    fi
}

# -----------------------------------------------------------------------------
# Project discovery
# -----------------------------------------------------------------------------

scan_projects() {
    # Returns newline-separated list of dirs containing astro.config.mjs,
    # relative to ORIGIN_DIR, depth 3. Empty if none found.
    # Sites under STARLIGHT_HOME (external sites) are listed too, by absolute
    # path, since they live outside the directory the TUI was started from.
    {
        find "$ORIGIN_DIR" -maxdepth 3 -name "astro.config.mjs" 2>/dev/null \
            | sed "s|/astro.config.mjs||" \
            | sed "s|^${ORIGIN_DIR}/||" \
            | sed "s|^${ORIGIN_DIR}$|.|" \
            | sort
        if [[ -d "$STARLIGHT_HOME" && "$STARLIGHT_HOME" != "$ORIGIN_DIR"* ]]; then
            find "$STARLIGHT_HOME" -mindepth 2 -maxdepth 2 -name "astro.config.mjs" 2>/dev/null \
                | sed "s|/astro.config.mjs||" | sort
        fi
    }
}

